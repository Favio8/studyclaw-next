/**
 * x 轴镜像：把 path 里的每对 (x, y) 数值替换为 (240-x, y)。
 * 只处理命令参数里的数值对，与原型实现逐字符等价。
 */
export function mir(d: string): string {
  return d.replace(
    /(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)/g,
    (_m: string, x: string, y: string) => `${240 - parseFloat(x)} ${y}`,
  );
}

